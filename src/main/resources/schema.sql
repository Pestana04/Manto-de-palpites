CREATE TABLE IF NOT EXISTS participants (
 id UUID PRIMARY KEY, token_hash VARCHAR(64) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL, photo CLOB NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS fixtures (
 id BIGINT PRIMARY KEY, kickoff TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(10) NOT NULL, home VARCHAR(120) NOT NULL, away VARCHAR(120) NOT NULL,
 home_goals INT, away_goals INT, league_id BIGINT NOT NULL, league VARCHAR(150) NOT NULL,
 season INT NOT NULL, round_name VARCHAR(150) NOT NULL
);
CREATE TABLE IF NOT EXISTS predictions (
 participant_id UUID NOT NULL REFERENCES participants(id), fixture_id BIGINT NOT NULL REFERENCES fixtures(id),
 home INT NOT NULL CHECK(home BETWEEN 0 AND 30), away INT NOT NULL CHECK(away BETWEEN 0 AND 30),
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL, PRIMARY KEY(participant_id,fixture_id)
);
CREATE TABLE IF NOT EXISTS cache (cache_key VARCHAR(100) PRIMARY KEY, payload CLOB NOT NULL);
